const mod={exports:{}};new Function('exports','require','module',ts.transpileModule(fs.readFileSync('lib/course-progress.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText)(mod.exports,require,mod);
const {normalizeCourse,courseProgress}=mod.exports;
const lesson=(id,videoUrl='https://example.com/'+id)=>({id,title:id,videoUrl,materialUrl:''});
const course={modules:[{title:'Base',lessons:[lesson('a'),lesson('b'),lesson('draft','')]}]};
